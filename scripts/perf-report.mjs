#!/usr/bin/env node
// Turns the JSON reports in _perf/ into markdown / console tables. No dependencies.
//   bun scripts/perf-report.mjs              write docs/operations/PERFORMANCE_RESULTS.md (last 10 runs)
//   bun scripts/perf-report.mjs --compare [new.json]
//        print a table: new run (default: newest file) vs the previous file; regressions > 25% are marked
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PERF_DIR = join(ROOT, "_perf");
const OUT = join(ROOT, "docs/operations/PERFORMANCE_RESULTS.md");
const REGRESSION_PCT = 25;

export function listRuns(dir = PERF_DIR) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => ({ file: f, path: join(dir, f), data: JSON.parse(readFileSync(join(dir, f), "utf8")) }))
    .sort((a, b) => String(a.data.date ?? a.file).localeCompare(String(b.data.date ?? b.file)) || a.file.localeCompare(b.file));
}

/** Every object under `scenarios` that carries a p95 becomes one metric: name -> {p50,p95,p99,max}. */
export function flatten(report) {
  const metrics = {};
  const walk = (node, path) => {
    if (!node || typeof node !== "object") return;
    if (typeof node.p95 === "number") {
      metrics[path.join(".")] = node;
      return;
    }
    for (const [k, v] of Object.entries(node)) walk(v, [...path, k]);
  };
  walk(report.scenarios ?? {}, []);
  return metrics;
}

const fmt = (n) => (typeof n === "number" ? n.toFixed(1) : "-");

function compare(newRun, prevRun) {
  const a = flatten(newRun.data);
  const b = prevRun ? flatten(prevRun.data) : {};
  const rows = [];
  let regressions = 0;
  for (const name of Object.keys(a).sort()) {
    const cur = a[name].p95;
    const prev = b[name]?.p95;
    let change = "n/a";
    let mark = "";
    if (prev === 0 && cur > 0) {
      change = "+∞%";
      mark = "  <-- REGRESSION";
      regressions++;
    } else if (typeof prev === "number" && prev > 0) {
      const pct = ((cur - prev) / prev) * 100;
      change = `${pct >= 0 ? "+" : ""}${pct.toFixed(0)}%`;
      if (pct > REGRESSION_PCT) {
        mark = "  <-- REGRESSION";
        regressions++;
      }
    }
    rows.push(`${name.padEnd(62)} ${fmt(prev).padStart(9)} ${fmt(cur).padStart(9)} ${change.padStart(8)}${mark}`);
  }
  const head = `${"metric (p95 ms)".padEnd(62)} ${"previous".padStart(9)} ${"current".padStart(9)} ${"change".padStart(8)}`;
  return { text: [head, ...rows].join("\n"), regressions };
}

function report(runs) {
  const last = runs.slice(-10);
  const names = [...new Set(last.flatMap((r) => Object.keys(flatten(r.data))))].sort();
  const lines = [
    "# Performance results",
    "",
    "Generated by `bun scripts/perf-report.mjs` from `_perf/*.json` (not committed). p95 in milliseconds, last 10 runs, oldest first.",
    "See [PERFORMANCE_TESTS.md](PERFORMANCE_TESTS.md) for how to read the numbers. `*` marks a modified working tree; `?` means its state was not recorded. Older runs may include estimated trace stages that the current runner no longer reports.",
    "",
  ];
  if (last.length === 0) {
    lines.push("No runs recorded yet. Run `scripts/test-perf.sh`.", "");
    return lines.join("\n");
  }
  const cols = last.map((r) => `${String(r.data.date ?? r.file).slice(0, 10)} ${String(r.data.commit ?? "").slice(0, 7)}${r.data.gitDirty === true ? "*" : r.data.gitDirty === false ? "" : "?"}`);
  lines.push(`| metric | ${cols.join(" | ")} |`, `| --- | ${cols.map(() => "---:").join(" | ")} |`);
  for (const n of names) {
    const cells = last.map((r) => fmt(flatten(r.data)[n]?.p95));
    lines.push(`| \`${n}\` | ${cells.join(" | ")} |`);
  }
  lines.push("");
  return lines.join("\n");
}

const args = process.argv.slice(2);
const runs = listRuns();
if (args[0] === "--compare") {
  const target = args[1] ? resolve(args[1]) : null;
  const idx = target ? runs.findIndex((r) => r.path === target) : runs.length - 1;
  if (idx < 0) {
    console.error("perf-report: run file not found in _perf/");
    process.exit(2);
  }
  const { text, regressions } = compare(runs[idx], runs[idx - 1]);
  console.log(idx === 0 ? "(no previous run to compare with)" : `compared with ${runs[idx - 1].file}`);
  console.log(text);
  if (regressions > 0) console.log(`\n${regressions} metric(s) regressed by more than ${REGRESSION_PCT}%`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, report(runs));
  console.log(`wrote ${OUT} (${Math.min(runs.length, 10)} run(s))`);
}
