#!/usr/bin/env python3
"""Translates the D1 (SQLite) triggers to PL/pgSQL trigger functions.

SQLite trigger WHEN clauses may contain subqueries, PostgreSQL ones may not,
so every condition moves into the function body. Inserts into the
canonical history serialise on a transaction-scoped advisory lock (D1 had a
single writer; PostgreSQL needs this for the MAX(sequence)+1 pattern).
"""
import re, sys

src = open(sys.argv[1]).read()
trigs = [x.strip().rstrip(';') for x in src.split(';\n\n') if x.strip().startswith('CREATE TRIGGER')]

# Columns typed timestamptz in the generated schema end with _at.
def iso_wrap(expr):
    return re.sub(r'\b((?:NEW|OLD|wr|cr|m)\.\w+_at)\b', r'syntila_iso(\1)', expr)

def split_args(s):
    out, depth, cur, q = [], 0, '', False
    for ch in s:
        if ch == "'": q = not q
        if not q:
            if ch == '(': depth += 1
            elif ch == ')': depth -= 1
            elif ch == ',' and depth == 0:
                out.append(cur); cur = ''; continue
        cur += ch
    out.append(cur)
    return [a.strip() for a in out]

def replace_calls(sql, fname, fn):
    out, i = '', 0
    pat = re.compile(r'\b' + fname + r'\(', re.I)
    while True:
        m = pat.search(sql, i)
        if not m:
            return out + sql[i:]
        out += sql[i:m.start()]
        depth, j = 1, m.end()
        while depth:
            if sql[j] == '(':
                depth += 1
            elif sql[j] == ')':
                depth -= 1
            j += 1
        out += fn(split_args(sql[m.end():j - 1]))
        i = j

def conv(sql):
    sql = re.sub(r"^SELECT CASE WHEN (.*) THEN RAISE\(ABORT,\s*('(?:[^']|'')*')\)\s*END$",
                 r"IF \1 THEN RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = \2; END IF", sql.strip(), flags=re.S)
    sql = replace_calls(sql, 'json_object', lambda a: 'jsonb_build_object(' + ', '.join(iso_wrap(x) for x in a) + ')::text')
    sql = replace_calls(sql, 'json_extract', lambda a: f"({a[0]}::jsonb #>> '{{{a[1].strip(chr(39))[2:].replace('.', ',')}}}')")
    sql = replace_calls(sql, 'MIN', lambda a: f'LEAST({a[0]}, {a[1]})' if len(a) == 2 else f'MIN({a[0]})')
    sql = replace_calls(sql, 'MAX', lambda a: f'GREATEST({a[0]}, {a[1]})' if len(a) == 2 else f'MAX({a[0]})')
    sql = sql.replace("strftime('%Y-%m-%dT%H:%M:%fZ', 'now')", 'now()')
    sql = re.sub(r"typeof\(([\w.]+)\)\s*!=\s*'integer'", 'FALSE', sql)
    sql = re.sub(r'\bIS NOT (?!NULL\b|DISTINCT\b|TRUE\b|FALSE\b)', 'IS DISTINCT FROM ', sql)
    sql = re.sub(r'\bIS (?!NOT\b|NULL\b|DISTINCT\b|TRUE\b|FALSE\b|JSON\b)', 'IS NOT DISTINCT FROM ', sql)
    sql = re.sub(r"substr\(([\w.]+),\s*(\d+),\s*(\d+)\)", r'substr(\1, \2, \3)', sql)
    sql = re.sub(r"([\w.()]+)\s+NOT GLOB\s+'\*\[\^0-9a-f\]\*'", r"\1 ~ '^[0-9a-f]*$'", sql)
    # Numeric JSON fields stored into bigint columns / compared with bigint.
    sql = re.sub(r"\(((?:NEW|OLD)\.permission_snapshot_json::jsonb #>> '\{(?:profileReleaseVersion|baseContextRevision)\}')\)", r'(\1)::bigint', sql)
    sql = re.sub(r"SELECT RAISE\(ABORT,\s*('(?:[^']|'')*')\)", r"RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = \1", sql)
    return sql

out = ['-- Triggers translated from D1 (generated by scripts/internal/d1-to-postgres-schema.py, reviewed).',
       "CREATE FUNCTION syntila_iso(ts timestamptz) RETURNS text LANGUAGE sql IMMUTABLE AS",
       "$$ SELECT to_char(ts AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"') $$;", '']
for t in trigs:
    m = re.match(r'CREATE TRIGGER (\w+)\s+(BEFORE|AFTER)\s+(INSERT|DELETE|UPDATE(?: OF [\w,\s]+?)?)\s+ON\s+"?(\w+)"?\s*(?:WHEN\s+(.*?))?\s*BEGIN\s+(.*)\s*END$', t, re.S)
    if not m:
        sys.exit('cannot parse: ' + t[:120])
    name, timing, event, table, when, body = m.groups()
    body = body.strip()
    stmts = [s.strip() for s in body.split(';') if s.strip()]
    lines = []
    for s in stmts:
        s = conv(s)
        if 'conversation_history_entries' in s and s.upper().startswith('INSERT'):
            lines.append("PERFORM pg_advisory_xact_lock(hashtext('syntila.conversation_history'));")
        lines.append(s + ';')
    ret = 'OLD' if event == 'DELETE' else 'NEW'
    fn_body = '\n    '.join(lines)
    if when:
        fn_body = f'IF {conv(when.strip())} THEN\n    {fn_body}\n  END IF;'
    out.append(f'CREATE FUNCTION {name}_fn() RETURNS trigger LANGUAGE plpgsql AS $$\nBEGIN\n  {fn_body}\n  RETURN {ret};\nEND $$;')
    out.append(f'CREATE TRIGGER {name} {timing} {event} ON {table} FOR EACH ROW EXECUTE FUNCTION {name}_fn();\n')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(trigs), 'triggers')
